const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const shellPath = path.join(root, 'src', 'App.svelte');
assert.ok(fs.existsSync(shellPath), 'Svelte app shell should exist');
const shell = fs.readFileSync(shellPath, 'utf8');
const de = fs.readFileSync(path.join(root, 'src/lib/locales/de.ts'), 'utf8');
const en = fs.readFileSync(path.join(root, 'src/lib/locales/en.ts'), 'utf8');
assert.match(html, /<html lang="de">/);
for (const label of ['Stickerwerkstatt', 'Motive', 'Schnittkante', 'Bogen & Export']) assert.ok(de.includes(label), `missing ${label}`);
for (const label of ['Artwork', 'Cut Line', 'Sheet & Export']) assert.ok(en.includes(label), `missing ${label}`);
assert.match(shell, /setLocale\('de'\)/);
assert.match(shell, /setLocale\('en'\)/);
assert.match(shell, /aria-pressed/);
assert.match(shell, /guide\.uploadBody/);
assert.match(shell, /guide\.cricutBody/);
for (const old of ['Drop sticker images here', 'Export Full Sticker Sheet', 'Download sheet PDF', 'Using the files with a cutter']) assert.ok(!shell.includes(old), `English UI remains: ${old}`);
for (const old of ['assets', 'guide.html', 'src/app', 'sticker-tool-offline.zip']) assert.ok(!fs.existsSync(path.join(root, old)), `legacy file remains: ${old}`);
console.log('German shell and removal of legacy app, illustrations and sample OK');
